  function detect() {
    let saved = null;
    try { saved = localStorage.getItem('ss.lang'); } catch {}
    if (saved && STR[saved]) return saved;
    for (const l of navigator.languages || [navigator.language || 'en']) {
      if (/^pt/i.test(l)) return 'pt-BR';
      if (/^es/i.test(l)) return 'es';
      if (/^en/i.test(l)) return 'en';
    }
    return 'en';
  }

  const lang = detect();

  // t('chat.joined', { name: 'Ana' }) -> 'Ana entrou'. Falls back to English, then to the key.
  function t(key, vars) {
    let s = STR[lang][key] ?? STR.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }

  // Static page text: data-i18n (text), data-i18n-html, data-i18n-title, data-i18n-placeholder.
  function apply(root = document) {
    document.documentElement.lang = lang;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  }

  function setLang(code) {
    if (!STR[code] || code === lang) return;
    try { localStorage.setItem('ss.lang', code); } catch {}
    location.reload();
  }

  return { t, apply, lang, LANGS, setLang };
